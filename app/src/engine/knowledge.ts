let factIdSeq = 0;
function nextFactId(): string {
  factIdSeq += 1;
  return `kf_${Date.now()}_${factIdSeq}`;
}

/** Собрать подмножество фактов с индивидуальным confidence */
export function buildKnowledgeBaseFromPool(
  era: WorldEra,
  professionKey: string,
  baseConfidence = 0.85
): NPCKnowledgeBase {
  const eraPools = POOLS[era] || POOLS.medieval;
  const pool = eraPools[professionKey] || eraPools.default;
  const count = Math.min(pool.factTexts.length, 5 + Math.floor(Math.random() * 8));
  const shuffled = [...pool.factTexts].sort(() => Math.random() - 0.5).slice(0, Math.max(3, Math.min(count, pool.factTexts.length)));

  const facts: KnowledgeFact[] = shuffled.map((text) => ({
    id: nextFactId(),
    text,
    confidence: Math.min(1, baseConfidence * (0.92 + Math.random() * 0.08))
  }));

  return {
    field: pool.field,
    fieldKeys: [...pool.fieldKeys],
    facts,
    confidence: baseConfidence
  };
}

/** Нормализация строки для грубого поиска ключевых слов */
function norm(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/[^a-zа-яё0-9\s]/gi, ' ');
}

/**
 * Подобрать NPC-эксперта по области (для ответа «спроси у …»).
 */
export function findExpertForField(npcs: NPC[], fieldFragment: string, excludeId?: string): NPC | null {
  const n = norm(fieldFragment);
  let best: NPC | null = null;
  let score = 0;
  for (const npc of npcs) {
    if (excludeId && npc.id === excludeId) continue;
    const kb = npc.knowledgeBase;
    if (!kb) continue;
    let s = 0;
    if (norm(kb.field).includes(n) || n.includes(norm(kb.field))) s += 3;
    for (const k of kb.fieldKeys || []) {
      if (n.includes(norm(k)) || norm(k).length > 2 && n.includes(norm(k))) s += 2;
    }
    if (s > score) {
      score = s;
      best = npc;
    }
  }
  return best;
}
